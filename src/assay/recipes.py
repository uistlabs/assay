from assay.config import DEFAULT_GATE, GateThresholds

_VALID_MODES = ("chat", "completion")


@dataclass(frozen=True)
class Calib:
    dataset: str
    split: str
    num_samples: int
    max_seq_len: int


@dataclass(frozen=True)
class Eval:
    # Each accuracy task carries its FULLY-QUALIFIED lm-eval metric key, incl. any
    # filter suffix (e.g. gpqa reports both exact_match,flexible-extract and
    # exact_match,strict-match - naming the filter removes the ambiguity).
    accuracy_tasks: tuple[tuple[str, str], ...]
    perplexity: tuple[str, str] | None      # (task, metric) or None to skip the ppl gate
    mode: str                                # "chat" | "completion"
    gen_kwargs: dict | None                  # sampling for generative tasks; global to the run
    system_prompt: str | None                # None => no system prompt (R1 requires this)
    prompt_prefix: str | None                # forced assistant-turn prefix, e.g. "<think>\n"
    # Targeted multi-sampling: task -> sample count K (avg@K). Empty => every task
    # single-sampled (today's behavior). Spend K only where stderr is large: aime
    # (n=30, ~9pt stderr) needs it; minerva/gpqa are already tight.
    repeats: dict[str, int] = field(default_factory=dict)


@dataclass(frozen=True)
class Recipe:
    slug: str
    base_model: str
    quant_scheme: str
    calib: Calib
    eval: Eval
    gate: GateThresholds | None              # None => DEFAULT_GATE
    tags: tuple[str, ...]
    # SPDX id for the card's front matter. A quantization is a derivative work, so this
    # must track the BASE MODEL's license - it is not a constant. It was hardcoded to
    # "apache-2.0" in publish.py, which silently misdeclared the R1 card (upstream
    # DeepSeek-R1-Distill-Qwen-7B is MIT). Defaulted empty and REQUIRED by
    # validate_recipe, which load_config runs before any GPU spend: a new recipe cannot
    # publish under an unstated license, and cannot inherit a wrong one by omission.
    license: str = ""
    # Base-model identity pins (F-015/F-027), generated by scripts/pin_base_files.py.
    # base_revision is the upstream COMMIT sha the pins were taken at - never a branch
    # or tag, which is exactly the moving target the pin removes. base_files maps
    # repo-relative file -> sha256 covering config.json, the safetensors index,
    # tokenizer_config.json (it carries the chat template driving calibration), and
    # the weight shards. verify.py checks the staged volume against this map in-pod,
    # BEFORE quantize: a mis-staged or partially re-staged volume would otherwise
    # publish the wrong model under a correct-looking card, still marked pristine.
    # The trust anchor is deliberately the reviewed GIT recipe, not a staging-time
    # manifest on the volume - a manifest anchors trust to the same mutable volume
    # being validated.
    base_revision: str = ""
    base_files: dict[str, str] = field(default_factory=dict)

    @property
    def accuracy_task_names(self) -> tuple[str, ...]:
        return tuple(task for task, _ in self.eval.accuracy_tasks)

    @property
    def perplexity_task_name(self) -> str | None:
        return None if self.eval.perplexity is None else self.eval.perplexity[0]

    @property
    def gate_or_default(self) -> GateThresholds:
        return self.gate or DEFAULT_GATE


