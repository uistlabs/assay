def get_recipe(slug: str) -> Recipe:
    try:
        return RECIPES[slug]
    except KeyError:
        raise KeyError(
            f"unknown recipe {slug!r}; valid slugs: {', '.join(sorted(RECIPES))}"
        ) from None


def validate_recipe(recipe: Recipe) -> None:
    """Cheap structural validation - catch a malformed recipe in milliseconds,
    before any paid GPU work. Does NOT hit the network (task existence is proven
    on metal)."""
    if not recipe.base_model:
        raise ValueError(
            f"recipe {recipe.slug!r}: base_model is required (got empty/unset - check "
            "ASSAY_BASE_MODEL if this was an env override)")
    if not recipe.quant_scheme:
        raise ValueError(
            f"recipe {recipe.slug!r}: quant_scheme is required (got empty/unset - check "
            "ASSAY_QUANT_SCHEME if this was an env override)")
    if not recipe.calib.dataset:
        raise ValueError(
            f"recipe {recipe.slug!r}: calib.dataset is required (got empty/unset - check "
            "ASSAY_CALIB_DATASET if this was an env override)")
    if not recipe.calib.split:
        raise ValueError(
            f"recipe {recipe.slug!r}: calib.split is required (got empty/unset - check "
            "ASSAY_CALIB_SPLIT if this was an env override)")
    ev = recipe.eval
    if not ev.accuracy_tasks:
        raise ValueError(f"recipe {recipe.slug!r}: needs at least one accuracy task")
    if ev.mode not in _VALID_MODES:
        raise ValueError(f"recipe {recipe.slug!r}: mode must be one of {_VALID_MODES}, got {ev.mode!r}")
    if ev.prompt_prefix is not None and ev.mode != "chat":
        raise ValueError(
            f"recipe {recipe.slug!r}: prompt_prefix requires mode='chat' (it is a "
            "forced assistant-turn prefix rendered through the chat template)")
    for task, metric in ev.accuracy_tasks:
        if not task or not metric:
            raise ValueError(f"recipe {recipe.slug!r}: empty task/metric in accuracy_tasks: {(task, metric)!r}")
        if "," not in metric:
            raise ValueError(
                f"recipe {recipe.slug!r}: accuracy metric key {metric!r} for task {task!r} "
                "must be fully qualified with its lm-eval filter suffix (e.g. 'acc,none', "
                "'exact_match,strict-match')")
    for rtask, rk in ev.repeats.items():
        if rtask not in recipe.accuracy_task_names:
            raise ValueError(
                f"recipe {recipe.slug!r}: repeats key {rtask!r} is not one of the "
                f"recipe's accuracy tasks {recipe.accuracy_task_names}")
        if not isinstance(rk, int) or rk < 1:
            raise ValueError(
                f"recipe {recipe.slug!r}: repeats[{rtask!r}] must be an int >= 1, got {rk!r}")
    if ev.perplexity is not None:
        ptask, pmetric = ev.perplexity
        if not ptask or not pmetric:
            raise ValueError(f"recipe {recipe.slug!r}: perplexity must be (task, metric) or None")
    if not recipe.tags:
        raise ValueError(f"recipe {recipe.slug!r}: at least one tag is required for the model card")
    # A criteria-free gate is a false-certification hazard: an EXPLICIT all-None
    # GateThresholds is truthy, so gate_or_default does NOT substitute DEFAULT_GATE,
    # and evaluate_gate then fires zero criteria and PASSES any quantization -> the
    # checkpoint publishes and is DOI-minted on no evidence. gate=None is the supported
    # "use DEFAULT_GATE" path; a criteria-free explicit gate must be rejected here.
    if recipe.gate is not None and not any((
            recipe.gate.min_mean_retention is not None,
            recipe.gate.max_single_drop_pts is not None,
            recipe.gate.max_ppl_increase is not None,
            recipe.gate.k_stderr is not None)):
        raise ValueError(
            f"recipe {recipe.slug!r}: gate has no active criteria (all thresholds are "
            "None). A criteria-free gate would PASS any quantization and publish a false "
            "certification. Set at least one threshold, or use gate=None for DEFAULT_GATE.")
    # Significance support matrix (BITE 2, D7): the paired test rests on the
    # pooled-mean identity, which holds only for mean-aggregated scalar per-item
    # metrics. A perplexity-family metric under a k_stderr gate would pass config and
    # then fail AFTER a paid eval (tuple per-item values, no mean identity), so it is
    # refused here at $0. This list names known NON-mean aggregations, not allowed
    # metrics - a new mean-aggregated metric needs no edit here; the authoritative
    # runtime control is the per-side reconciliation assert in pairing.collect_items.
    if recipe.gate is not None and recipe.gate.k_stderr is not None:
        non_mean = ("word_perplexity", "byte_perplexity", "bits_per_byte")
        for task, metric in recipe.eval.accuracy_tasks:
            if metric.split(",", 1)[0] in non_mean:
                raise ValueError(
                    f"recipe {recipe.slug!r}: accuracy task {task!r} uses {metric!r} "
                    "under a k_stderr gate, but the paired significance test requires "
                    "a mean-aggregated per-item metric (perplexity aggregates as "
                    "weighted perplexity and its per-item values are tuples). Put it "
                    "in eval.perplexity, where the ratio hard bar applies.")
    # Base-model identity pins (F-015/F-027): both halves or neither. The sha map is
    # only meaningful AT the revision it was generated from, and a pinned revision
    # with no file map verifies nothing.
    if bool(recipe.base_files) != bool(recipe.base_revision):
        raise ValueError(
            f"recipe {recipe.slug!r}: base_revision and base_files must be set together "
            "- the sha256 map is only meaningful at the commit it was generated from. "
            "Regenerate both with scripts/pin_base_files.py.")
    if recipe.base_revision and not re.fullmatch(r"[0-9a-f]{40}", recipe.base_revision):
        raise ValueError(
            f"recipe {recipe.slug!r}: base_revision {recipe.base_revision!r} must be the "
            "40-hex upstream commit sha - a branch or tag name is a moving target, which "
            "is exactly what the pin exists to remove (scripts/pin_base_files.py emits it).")
    for pin_path, digest in recipe.base_files.items():
        if not pin_path or pin_path.startswith("/") or ".." in pin_path:
            raise ValueError(
                f"recipe {recipe.slug!r}: base_files key {pin_path!r} must be a relative "
                "path inside the base model repo (no leading '/', no '..').")
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError(
                f"recipe {recipe.slug!r}: base_files[{pin_path!r}] must be a 64-hex "
                f"sha256, got {digest!r}. Regenerate with scripts/pin_base_files.py.")
    # Checked LAST so the more specific structural errors above keep reporting first.
    # A quantization is a derivative work: publishing it under a license the base model
    # did not grant is a legal misstatement on the card, not a cosmetic one. There is
    # deliberately no default to inherit - the old hardcoded "apache-2.0" is exactly how
    # the R1 card (base model: MIT) came to declare the wrong license.
    if not recipe.license:
        raise ValueError(
            f"recipe {recipe.slug!r}: license is required - set it to the SPDX id of the "
            f"BASE MODEL's license (check {recipe.base_model or '<base_model>'} on the Hub). "
            "It is published in the model card's front matter, so it must not be guessed "
            "or copied from another recipe.")
